export const getShop = (id) => {
  // Check dynamically saved seller stores first
  try {
    const raw = localStorage.getItem('urban:seller_store_profile');
    if (raw) {
      const customStore = JSON.parse(raw);
      if (customStore && (customStore.id === id || customStore.handle === id)) {
        return customStore;
      }
    }
  } catch {
    // ignore
  }
  return curatedShops.find((s) => s.id === id);
};
